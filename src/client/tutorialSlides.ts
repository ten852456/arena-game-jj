  `<span class="tut-grid">${rows
    .map((r) => `<span>${[...r].map((c) => `<i class="${c === '.' ? '' : c === '*' ? 'hot' : 'on'}"></i>`).join('')}</span>`)
    .join('')}</span>${hot}`;

